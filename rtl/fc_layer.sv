// =============================================================================
// fc_layer.sv — Lớp fully-connected dùng chung cho lớp 1 và lớp 2
// -----------------------------------------------------------------------------
// Tính OUT neuron theo từng nhóm P neuron song song (P khối mac_pe):
//   với mỗi nhóm g = 0 .. OUT/P - 1:
//     S_LOAD : nạp bias của P neuron vào P bộ cộng dồn
//     S_MAC  : quét i = 0 .. IN-1, mỗi chu kỳ đọc 1 đầu vào x[i] và
//              1 word ROM chứa P trọng số W[g*P+k][i], P MAC chạy cùng lúc
//     S_DRAIN: chờ phép MAC cuối
//     S_WRITE: lần lượt đưa P kết quả qua khối requant rồi ghi ra ngoài
//   S_FLUSH: chờ pipeline requant xong rồi báo done
// Số chu kỳ ≈ (OUT/P) * (IN + P + 3)
//
// Bố cục ROM (quy ước chung với bên AI):
//   địa chỉ = g*IN + i,   word[8k+7:8k] = W[g*P + k][i]
//
// LAYER = 1 dùng w1_rom + b1_val(), LAYER = 2 dùng w2_rom + b2_val()
// (bias nằm trong tinyml_pkg, 2 ROM w1_rom / w2_rom nằm ở cuối file này,
//  không cần file .mem)
//
// RELU = 1 (lớp ẩn) : out = clamp((acc*M1 + 2^23) >>> 24, 0, 127)  — giống requant_relu()
// RELU = 0 (lớp ra) : out = acc (logit int32)
// =============================================================================
module fc_layer
    import tinyml_pkg::*;
#(
    parameter int    IN     = N_IN,
    parameter int    OUT    = N_HID,
    parameter int    P      = PE1,
    parameter int    LAYER  = 1,          // 1 = lớp ẩn, 2 = lớp ra
    parameter bit    RELU   = 1'b1,
    localparam int   IN_AW  = $clog2(IN),
    localparam int   OUT_AW = $clog2(OUT)
) (
    input  logic              clk,
    input  logic              rst,
    input  logic              start,      // xung từ top_fsm
    output logic              done,       // xung 1 chu kỳ sau lần ghi cuối
    output logic              busy,

    // Cổng đọc bộ đệm đầu vào (buf_ram, trễ đọc 1 chu kỳ)
    output logic [IN_AW-1:0]  x_addr,
    input  act_t              x_data,

    // Cổng ghi kết quả
    output logic              out_we,
    output logic [OUT_AW-1:0] out_addr,
    output acc_t              out_data
);
    localparam int G     = OUT / P;            // số nhóm neuron
    localparam int DEPTH = G * IN;             // số word ROM
    localparam int AW    = $clog2(DEPTH);
    localparam int GW    = (G > 1) ? $clog2(G) : 1;
    localparam int KW    = (P > 1) ? $clog2(P) : 1;

    // ---------------- ROM trọng số (BRAM) và bias ----------------
    logic [AW-1:0]         w_addr;
    logic [P*WEIGHT_W-1:0] w_word;            // đọc ROM trễ 1 chu kỳ

    generate
        if (LAYER == 1) begin : g_rom
            w1_rom u_rom (.clk(clk), .addr(w_addr), .data(w_word));
        end else begin : g_rom
            w2_rom u_rom (.clk(clk), .addr(w_addr), .data(w_word));
        end
    endgenerate

    function automatic bias_t bias_of(input int i);
        return (LAYER == 1) ? b1_val(i) : b2_val(i);
    endfunction

    // ---------------- FSM ----------------
    typedef enum logic [2:0] { S_IDLE, S_LOAD, S_MAC, S_DRAIN, S_WRITE, S_FLUSH } state_t;
    state_t state;

    logic [IN_AW-1:0] i_cnt;     // chỉ số đầu vào
    logic [GW-1:0]    g_cnt;     // nhóm neuron
    logic [KW-1:0]    k_cnt;     // neuron trong nhóm (lúc ghi)
    logic             flush_cnt;
    logic             mac_v;     // x_data và w_word của chu kỳ trước hợp lệ

    assign x_addr = i_cnt;
    assign busy   = (state != S_IDLE);

    always_ff @(posedge clk) begin
        if (rst) begin
            state     <= S_IDLE;
            i_cnt     <= '0;
            g_cnt     <= '0;
            k_cnt     <= '0;
            w_addr    <= '0;
            mac_v     <= 1'b0;
            flush_cnt <= 1'b0;
            done      <= 1'b0;
        end else begin
            done  <= 1'b0;
            mac_v <= (state == S_MAC);
            unique case (state)
                S_IDLE: if (start) begin
                    g_cnt  <= '0;
                    w_addr <= '0;
                    state  <= S_LOAD;
                end
                S_LOAD: begin
                    i_cnt <= '0;
                    state <= S_MAC;
                end
                S_MAC: begin
                    i_cnt  <= i_cnt + 1'b1;
                    w_addr <= w_addr + 1'b1;
                    if (i_cnt == IN_AW'(IN - 1)) state <= S_DRAIN;
                end
                S_DRAIN: begin
                    k_cnt <= '0;
                    state <= S_WRITE;
                end
                S_WRITE: begin
                    k_cnt <= k_cnt + 1'b1;
                    if (k_cnt == KW'(P - 1)) begin
                        if (g_cnt == GW'(G - 1)) begin
                            flush_cnt <= 1'b0;
                            state     <= S_FLUSH;
                        end else begin
                            g_cnt <= g_cnt + 1'b1;
                            state <= S_LOAD;
                        end
                    end
                end
                S_FLUSH: begin                  // chờ 2 tầng pipeline requant
                    flush_cnt <= 1'b1;
                    if (flush_cnt) begin
                        done  <= 1'b1;
                        state <= S_IDLE;
                    end
                end
                default: state <= S_IDLE;
            endcase
        end
    end

    // ---------------- Mảng P khối MAC ----------------
    acc_t acc [P];
    genvar k;
    generate
        for (k = 0; k < P; k = k + 1) begin : g_pe
            mac_pe u_pe (
                .clk     (clk),
                .load    (state == S_LOAD),
                .load_val(bias_of(int'(g_cnt) * P + k)),
                .en      (mac_v),
                .w       (weight_t'(w_word[k*WEIGHT_W +: WEIGHT_W])),
                .x       (x_data),
                .acc     (acc[k])
            );
        end
    endgenerate

    // ---------------- Requant + ReLU dùng chung, pipeline 2 tầng ----------------
    // Tầng 1: chọn bộ cộng dồn, nhân với M1 (DSP)
    // Tầng 2: làm tròn, dịch số học, bão hoà [0, 127]
    logic                    p1_v, p2_v;
    logic [OUT_AW-1:0]       p1_addr, p2_addr;
    acc_t                    p1_acc;
    logic signed [RQ_W-1:0]  p1_prod, p1_shift;

    assign p1_shift = (p1_prod + (RQ_W'(1) <<< (SHIFT - 1))) >>> SHIFT;

    always_ff @(posedge clk) begin
        if (rst) begin
            p1_v <= 1'b0;
            p2_v <= 1'b0;
        end else begin
            p1_v <= (state == S_WRITE);
            p2_v <= p1_v;
        end
    end

    always_ff @(posedge clk) begin
        p1_addr <= OUT_AW'(int'(g_cnt) * P + int'(k_cnt));
        p1_acc  <= acc[k_cnt];
        p1_prod <= RQ_W'(acc[k_cnt]) * RQ_W'(M1);

        p2_addr <= p1_addr;
        if (!RELU)                            out_data <= p1_acc;
        else if (p1_shift < RQ_W'(ACT_MIN))   out_data <= acc_t'(ACT_MIN);
        else if (p1_shift > RQ_W'(ACT_MAX))   out_data <= acc_t'(ACT_MAX);
        else                                  out_data <= acc_t'(p1_shift);
    end

    assign out_we   = p2_v;
    assign out_addr = p2_addr;

endmodule

