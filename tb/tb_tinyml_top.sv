/* =============================================================================
 tb_tinyml_top.sv - Testbench for tinyml_top (board-independent top)
 -----------------------------------------------------------------------------
 The testbench acts as the PC and runs in 2 parts:
   Part 1: send n_img images over UART (1 Mbaud, 8N1). For each image, check:
           * busy goes high while computing
           * the character returned by the FPGA = '0' + the digit predicted
                by Python (tb_data_pkg)
           * result and result_valid are correct, err_seen stays 0
   Part 2: send an incomplete frame (100 bytes), then stay idle for > 10 ms
           -> the FPGA must drop the frame (err_seen = 1) and return no
              character, and the image sent afterwards must still produce
              the correct result
 Sample images come from tb_data_pkg (20 images embedded below, no .mem files needed).
 Optional: +ANH_VAO=<file> loads another sample set instead (written by
 pc/tinyml_web.py). File format, hex numbers separated by spaces/newlines:
     <count>
     <python digit> <true label> <784 pixel bytes, pixel 0 first>   (x count)
 With +ANH_VAO only Part 1 runs.
 Vivado: Set as Top (sim_1) -> Run Behavioral Simulation -> run all
 Each image is drawn in the Tcl Console with a virtual 7-segment display and LED row.
 Each image takes ~7.8 ms of simulation time (20 images ~ 175 ms).
 ============================================================================= */
