            12: return 9;
            13: return 0;
            14: return 1;
            15: return 5;
            16: return 9;
            17: return 7;
            18: return 3;
            19: return 4;
            default: return -1;
        endcase
    endfunction
endpackage

module tb_tinyml_top;
    import tinyml_pkg::*;
    import tb_data_pkg::*;

    localparam int  MAX_IMG = 64;
    localparam real BIT_NS = 1.0e9 / UART_BAUD;      // 1000 ns

    // ---------------- Clock, DUT ----------------
    logic   clk = 0, rst_btn = 1, uart_rxd = 1;
    logic   uart_txd, result_valid, busy, err_seen;
    digit_t result;
    always #5 clk = ~clk;                            // 100 MHz

    tinyml_top dut (.*);

    // LED 7 đoạn ảo: nối seg7 thật vào result để xem đúng mã board sẽ hiện
    logic [6:0] seg;
    logic       dp;
    logic [7:0] an;
    seg7 #(.N_AN(8)) u_seg7 (.digit(result), .valid(result_valid), .seg(seg), .dp(dp), .an(an));

    // ---------------- Bộ mẫu thử ----------------
    // Mặc định lấy từ tb_data_pkg; nếu có +ANH_VAO=<file> thì đọc file đó.
    logic [784*8-1:0] imgs [MAX_IMG];
    int               exps [MAX_IMG], labs [MAX_IMG];
    int               n_img = 0;
    bit               tu_file = 0;

    task automatic load_samples();
        string fname;
        int    f, v, k;
        if ($value$plusargs("ANH_VAO=%s", fname)) begin
            f = $fopen(fname, "r");
            if (f == 0) $display("Khong mo duoc %s -> dung %0d anh co san", fname, TB_N_IMG);
            else begin
                k = $fscanf(f, "%h", n_img);
                if (n_img > MAX_IMG) n_img = MAX_IMG;
                for (int n = 0; n < n_img; n++) begin
                    k = $fscanf(f, "%h", exps[n]);
                    k = $fscanf(f, "%h", labs[n]);
                    for (int p = 0; p < N_IN; p++) begin
                        k = $fscanf(f, "%h", v);
                        imgs[n][p*8 +: 8] = v[7:0];
                    end
                end
                $fclose(f);
                tu_file = 1;
                $display("Doc %0d anh tu %s", n_img, fname);
            end
        end
        if (!tu_file) begin
            n_img = TB_N_IMG;
            for (int n = 0; n < n_img; n++) begin
                imgs[n] = tb_image(n);
                exps[n] = tb_expected(n);
                labs[n] = tb_label(n);
            end
        end
    endtask

    // ---------------- PC giả lập ----------------
    task automatic pc_send(input logic [7:0] b);
        uart_rxd = 0; #(BIT_NS);                     // start
        for (int i = 0; i < 8; i++) begin uart_rxd = b[i]; #(BIT_NS); end
        uart_rxd = 1; #(BIT_NS);                     // stop
    endtask

    task automatic send_image(input int n);
        for (int p = 0; p < N_IN; p++) pc_send(imgs[n][p*8 +: 8]);
    endtask

    // Đếm số ký tự FPGA gửi về và lưu ký tự gần nhất
    int         n_rx = 0;
    logic [7:0] last_ch;
    initial forever begin
        logic [7:0] b;
        @(negedge uart_txd);                         // bit start
        #(BIT_NS * 1.5);                             // giữa bit D0
        for (int i = 0; i < 8; i++) begin b[i] = uart_txd; #(BIT_NS); end
        last_ch = b;
        n_rx++;
    end

    // Ghi nhận busy có lên 1 không
    bit saw_busy;
    always @(posedge clk) if (busy) saw_busy = 1;


    // ---------------- Hiển thị ra Tcl Console ----------------
    // Vẽ ảnh 28x28 (mỗi pixel 2 ký tự, càng đậm càng sáng) và bên phải là
    // LED 7 đoạn ảo (giải mã từ chân seg thật, tích cực mức thấp) + hàng LED.
    function automatic string px_char(input logic [7:0] v);
        if      (v < 8'd32)  return "  ";
        else if (v < 8'd96)  return "..";
        else if (v < 8'd160) return "++";
        else if (v < 8'd224) return "##";
        else                 return "@@";
    endfunction

    // 1 dòng của LED 7 đoạn phóng to (7 dòng x 9 cột). seg[0]=a ... seg[6]=g, 0 = sáng
    function automatic string seg_row(input int r, input logic [6:0] s);
        logic a, b, c, d, e, f, g;
        {g, f, e, d, c, b, a} = ~s;
        case (r)
            0:       return a ? " ####### " : "         ";
            1, 2:    return {f ? "#" : " ", "       ", b ? "#" : " "};
            3:       return g ? " ####### " : "         ";
            4, 5:    return {e ? "#" : " ", "       ", c ? "#" : " "};
            6:       return d ? " ####### " : "         ";
            default: return "         ";
        endcase
    endfunction

    task automatic show_result(input int n);
        logic [784*8-1:0] img;
        string line, leds;
        img = imgs[n];
        leds = "";
        for (int i = 9; i >= 0; i--) leds = {leds, (result_valid && result == digit_t'(i)) ? "O" : "."};
        $display("");
        $display("+--------------------------------------------------------+   Anh %0d", n);
        for (int r = 0; r < 28; r++) begin
            line = "|";
            for (int c = 0; c < 28; c++) line = {line, px_char(img[(r*28 + c)*8 +: 8])};
            line = {line, "|"};
            if (r >= 2 && r <= 8)  line = {line, "      ", seg_row(r - 2, seg)};
            if (r == 1)            line = {line, "   LED 7 doan (an[0]):"};
            if (r == 11)           line = {line, $sformatf("   FPGA tra ve : '%c' (ASCII 0x%02h)", last_ch, last_ch)};
            if (r == 12)           line = {line, $sformatf("   Nhan that   : %0d", labs[n])};
            if (r == 14)           line = {line, "   LED 9876543210"};
            if (r == 15)           line = {line, {"       ", leds}};
            if (r == 17)           line = {line, $sformatf("   busy=%b  err_seen=%b", busy, err_seen)};
            $display("%s", line);
        end
        $display("+--------------------------------------------------------+");
    endtask

    // ---------------- Ghi kết quả ra file cho trang Python (tinyml_viewer.py) ----------------
    // File nằm trong thư mục chạy mô phỏng: TINY_MNIST.sim/sim_1/behav/xsim/ket_qua_sim.txt
    // Mỗi ảnh 2 dòng:  IMG <n> <ky tu FPGA> <so Python> <nhan that> <ok> <ma ASCII hex>
    //                  784 pixel hex liền nhau (pixel 0 trước)
    int fd;
    initial fd = $fopen("ket_qua_sim.txt", "w");

    task automatic log_result(input int n, input bit ok);
        $fwrite(fd, "IMG %0d %c %0d %0d %0d %02h\n", n, last_ch, exps[n], labs[n], ok, last_ch);
        for (int p = 0; p < N_IN; p++) $fwrite(fd, "%02h", imgs[n][p*8 +: 8]);
        $fwrite(fd, "\n");
        $fflush(fd);
    endtask

    int errors = 0, correct_label = 0;

    task automatic check_image(input int n, input bit ghi = 1);
        int exp_d, rx0, err0;
        exp_d    = exps[n];
        err0     = errors;
        rx0      = n_rx;
        saw_busy = 0;
        send_image(n);
        #(BIT_NS * 60);                              // tính ~32 us + gửi 1 ký tự ~10 us
        if (!saw_busy) begin
            errors++; $display("SAI anh %0d: busy khong len 1", n);
        end else if (n_rx != rx0 + 1) begin
            errors++; $display("SAI anh %0d: nhan %0d ky tu (can 1)", n, n_rx - rx0);
        end else if (last_ch !== 8'h30 + exp_d[7:0]) begin
            errors++; $display("SAI anh %0d: FPGA tra '%c', Python = %0d", n, last_ch, exp_d);
        end else if (!result_valid || result !== digit_t'(exp_d)) begin
            errors++; $display("SAI anh %0d: result=%0d valid=%b", n, result, result_valid);
        end else if (busy) begin
            errors++; $display("SAI anh %0d: busy van = 1 sau khi xong", n);
        end else begin
            if (ghi && exp_d == labs[n]) correct_label++;
            $display("OK  anh %0d: FPGA tra '%c' (0x%02h) | Python %0d | nhan that %0d",
                     n, last_ch, last_ch, exp_d, labs[n]);
        end
        if (ghi) begin
            show_result(n);
            log_result(n, errors == err0);
        end
    endtask

    // ---------------- Kịch bản ----------------
    initial begin
        load_samples();
        #(BIT_NS * 3); rst_btn = 0; #(BIT_NS * 3);
        if (result_valid !== 1'b0 || busy !== 1'b0 || err_seen !== 1'b0 || uart_txd !== 1'b1) begin
            errors++; $display("SAI sau reset: valid=%b busy=%b err=%b txd=%b",
                               result_valid, busy, err_seen, uart_txd);
        end

        // ---- Phần 1: n_img ảnh liên tiếp ----
        $display("--- Phan 1: %0d anh qua UART ---", n_img);
        for (int n = 0; n < n_img; n++) check_image(n);
        if (err_seen) begin errors++; $display("SAI: err_seen = 1 du khong co loi"); end

        // ---- Phần 2: khung dở rồi ngừng > 10 ms (chỉ khi dùng mẫu có sẵn) ----
        if (!tu_file) begin
            int rx0;
            $display("--- Phan 2: khung do 100 byte, ngung 11 ms ---");
            rx0 = n_rx;
            for (int p = 0; p < 100; p++) pc_send(imgs[0][p*8 +: 8]);
            #(11_000_000);                           // 11 ms > GAP_TIMEOUT
            if (!err_seen) begin errors++; $display("SAI: khong bao bo khung (err_seen = 0)"); end
            else if (n_rx != rx0) begin errors++; $display("SAI: FPGA tra ky tu cho khung do"); end
            else $display("OK  khung do bi bo, err_seen = 1, khong tra ky tu");
            check_image(0, 0);                       // ảnh gửi sau vẫn phải đúng (không ghi file)
        end

        $display("----------------------------------------");
        $display("Dung nhan that: %0d/%0d anh", correct_label, n_img);
        if (errors == 0) $display("PASS tb_tinyml_top");
        else             $display("FAIL tb_tinyml_top (%0d loi)", errors);
        $fwrite(fd, "END %0d\n", errors);
        $fclose(fd);
        $display("Da ghi ket_qua_sim.txt -> mo tinyml_viewer.py de xem");
        $finish;
    end

    // Chống treo
    initial begin
        #(1_000_000_000);                            // 1 s, đủ cho 64 ảnh
        $display("FAIL tb_tinyml_top: qua thoi gian");
        $finish;
    end
endmodule
